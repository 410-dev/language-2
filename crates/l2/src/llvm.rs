fn esc_bytes(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if (0x20..0x7f).contains(&c) && c != b'"' && c != b'\\' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{:02X}", c);
        }
    }
    s
}

fn float_lit(v: f64, r: Repr) -> String {
    let v = if r == Repr::F32 { v as f32 as f64 } else { v };
    format!("0x{:016X}", v.to_bits())
}

fn int_kind(t: &Type) -> IntTy {
    match t.deref() {
        Type::Int(i) => *i,
        _ => IntTy::I64,
    }
}

fn float_kind(t: &Type) -> FloatTy {
    match t.deref() {
        Type::Float(f) => *f,
        _ => FloatTy::F64,
    }
}

impl<'p> ModGen<'p> {
    /// Returns the global name of a NUL-terminated string constant.
    fn cstr(&mut self, s: &str) -> String {
        let mut b = s.as_bytes().to_vec();
        b.push(0);
        if let Some(n) = self.strings.get(&b) {
            return n.clone();
        }
        let name = format!("@s.{}", self.strings.len());
        let _ = writeln!(self.globals, "{} = private unnamed_addr constant [{} x i8] c\"{}\"", name, b.len(), esc_bytes(&b));
        self.strings.insert(b, name.clone());
        name
    }

    fn list(&mut self, l: &[ClassId]) -> String {
        if let Some(i) = self.lists.iter().position(|x| x == l) {
            return format!("@cl.{}", i);
        }
        self.lists.push(l.to_vec());
        format!("@cl.{}", self.lists.len() - 1)
    }

    fn sig(&self, f: FuncId) -> (Vec<Repr>, Repr) {
        let func = &self.p.funcs[f as usize];
        let ps = func.params.iter().map(|p| repr(&func.locals[*p as usize].ty)).collect();
        (ps, repr(&func.ret))
    }

    fn class_table(&mut self) -> String {
        let p = self.p;
        let mut out = String::new();
        out.push_str("%ClassDesc = type { i32, ptr, i32, ptr, ptr, i32, ptr, ptr, ptr, ptr, ptr, i32 }\n");
        let mut entries = Vec::new();
        for (i, c) in p.classes.iter().enumerate() {
            let name = self.cstr(&c.name);
            let nf = c.fields.len();
            let (fnames, fnull) = if nf == 0 {
                ("null".to_string(), "null".to_string())
            } else {
                let names: Vec<String> = c.fields.iter().map(|f| format!("ptr {}", self.cstr(&f.name))).collect();
                let _ = writeln!(out, "@cf.{} = private constant [{} x ptr] [{}]", i, nf, names.join(", "));
                let nulls: Vec<String> = c.fields.iter().map(|f| format!("i8 {}", if f.ty.is_nullable() { 1 } else { 0 })).collect();
                let _ = writeln!(out, "@cn.{} = private constant [{} x i8] [{}]", i, nf, nulls.join(", "));
                (format!("@cf.{}", i), format!("@cn.{}", i))
            };
            let ifs = if c.ifaces.is_empty() {
                "null".to_string()
            } else {
                let items: Vec<String> = c.ifaces.iter().map(|x| format!("i32 {}", x)).collect();
                let _ = writeln!(out, "@ci.{} = private constant [{} x i32] [{}]", i, c.ifaces.len(), items.join(", "));
                format!("@ci.{}", i)
            };
            let f = |x: Option<FuncId>| x.map(|f| format!("@f.{}", f)).unwrap_or("null".into());
            entries.push(format!(
                "%ClassDesc {{ i32 {}, ptr {}, i32 {}, ptr {}, ptr {}, i32 {}, ptr {}, ptr {}, ptr {}, ptr {}, ptr {}, i32 {} }}",
                c.parent.map(|x| x as i64).unwrap_or(-1),
                name,
                nf,
                fnames,
                fnull,
                if c.is_throwable { 1 } else { 0 },
                f(c.to_string_fn),
                f(c.equals_fn),
                f(c.compare_fn),
                f(c.drop_fn),
                ifs,
                c.ifaces.len()
            ));
        }
        let _ = writeln!(out, "@l2.classes = private constant [{} x %ClassDesc] [\n  {}\n]", entries.len(), entries.join(",\n  "));
        let exc: Vec<String> = ExcKind::ALL.iter().map(|k| format!("i32 {}", p.exc_class(*k))).collect();
        let _ = writeln!(out, "@l2.exc = private constant [{} x i32] [{}]", exc.len(), exc.join(", "));
        out
    }

    fn dispatcher(&mut self, sid: SelectorId) -> String {
        let p = self.p;
        let sel = &p.selectors[sid as usize];
        let ret = repr(&sel.ret);
        let mut params = vec![Repr::Ptr];
        params.extend(sel.params.iter().map(repr));
        let plist: Vec<String> = params.iter().enumerate().map(|(i, r)| format!("{}{} %a{}", r.ll(), if *r == Repr::I1 { " zeroext" } else { "" }, i)).collect();
        let mut s = String::new();
        let _ = writeln!(s, "define internal {}{} @sel.{}({}) {{", attr(ret), ret.ll(), sid, plist.join(", "));
        let _ = writeln!(s, "entry:\n  %c = call i32 @l2_class_of(ptr %a0)");
        let impls: Vec<(usize, FuncId)> = p.classes.iter().enumerate().filter_map(|(i, c)| c.vtable.get(&sid).map(|f| (i, *f))).collect();
        let cases: Vec<String> = impls.iter().map(|(c, _)| format!("i32 {}, label %c{}", c, c)).collect();
        let _ = writeln!(s, "  switch i32 %c, label %fail [ {} ]", cases.join(" "));
        let args: Vec<String> = params.iter().enumerate().map(|(i, r)| format!("{}{} %a{}", r.ll(), if *r == Repr::I1 { " zeroext" } else { "" }, i)).collect();
        for (c, f) in &impls {
            let _ = writeln!(s, "c{}:", c);
            if ret == Repr::Void {
                let _ = writeln!(s, "  call void @f.{}({})\n  ret void", f, args.join(", "));
            } else {
                let _ = writeln!(s, "  %r{} = call {}{} @f.{}({})\n  ret {} %r{}", c, attr(ret), ret.ll(), f, args.join(", "), ret.ll(), c);
            }
        }
        let _ = writeln!(s, "fail:");
        for (i, r) in params.iter().enumerate() {
            if *r == Repr::Ptr {
                let _ = writeln!(s, "  call void @l2_free(ptr %a{})", i);
            }
        }
        if ret == Repr::Void {
            let _ = writeln!(s, "  ret void\n}}\n");
        } else {
            let _ = writeln!(s, "  ret {} {}\n}}\n", ret.ll(), ret.zero());
        }
        s
    }

    fn closure_wrapper(&mut self, f: FuncId) -> String {
        let (ps, ret) = self.sig(f);
        let plist: Vec<String> = ps.iter().enumerate().map(|(i, r)| format!("{}{} %a{}", r.ll(), if *r == Repr::I1 { " zeroext" } else { "" }, i)).collect();
        let mut s = String::new();
        let mut all = vec!["ptr %env".to_string()];
        all.extend(plist.clone());
        let _ = writeln!(s, "define internal {}{} @f.{}.clo({}) {{\nentry:", attr(ret), ret.ll(), f, all.join(", "));
        if ret == Repr::Void {
            let _ = writeln!(s, "  call void @f.{}({})\n  ret void\n}}\n", f, plist.join(", "));
        } else {
            let _ = writeln!(s, "  %r = call {}{} @f.{}({})\n  ret {} %r\n}}\n", attr(ret), ret.ll(), f, plist.join(", "), ret.ll());
        }
        s
    }

    fn main_fn(&mut self) -> String {
        let p = self.p;
        let mut s = String::new();
        let _ = writeln!(s, "define i32 @main(i32 %argc, ptr %argv) {{\nentry:");
        let _ = writeln!(s, "  call void @l2_rt_init(ptr @l2.classes, i32 {}, ptr @l2.exc, i32 {}, i32 %argc, ptr %argv)", p.classes.len(), ExcKind::ALL.len());
        for i in 0..p.globals.len() {
            let _ = writeln!(s, "  %g{} = call ptr @l2_cell_new(ptr null)\n  store ptr %g{}, ptr @g.{}", i, i, i);
        }
        let _ = writeln!(s, "  call void @f.{}()", p.init);
        let _ = writeln!(s, "  %p0 = load i8, ptr @L2_PENDING\n  %e0 = icmp ne i8 %p0, 0\n  br i1 %e0, label %fin, label %run");
        let _ = writeln!(s, "run:");
        let main_ret = repr(&p.funcs[p.main as usize].ret);
        let arg = if p.main_takes_args {
            let _ = writeln!(s, "  %args = call ptr @l2_args()");
            "ptr %args"
        } else {
            ""
        };
        let code = if main_ret == Repr::Void {
            let _ = writeln!(s, "  call void @f.{}({})", p.main, arg);
            "0".to_string()
        } else {
            let _ = writeln!(s, "  %rc = call {} @f.{}({})", main_ret.ll(), p.main, arg);
            "%rc".to_string()
        };
        let _ = writeln!(s, "  br label %fin\nfin:\n  %code = phi i32 [ 0, %entry ], [ {}, %run ]", code);
        let _ = writeln!(s, "  %r = call i32 @l2_rt_finish(i32 %code)\n  ret i32 %r\n}}");
        s
    }
}

