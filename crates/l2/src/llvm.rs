//! LLVM IR code generation (textual IR).
//!
//! Numbers and Booleans are kept unboxed in SSA registers / stack slots; every other value is
//! a pointer to a boxed runtime value managed by `l2-native-rt` (null = `Null`). See the
//! ownership protocol documented in `l2-native-rt`. Exceptions use a pending flag that is
//! checked after each call that may throw; the code then branches to the innermost landing
//! block (catch dispatch, finally, scope drops, or the function's exceptional exit).

use crate::hir::*;
use crate::types::*;
use l2_runtime::ops::{ArithOp, CmpOp};
use l2_runtime::{Builtin, ExcKind, FloatTy, IntTy};
use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Repr {
    I1,
    I8,
    I16,
    I32,
    I64,
    F32,
    F64,
    Ptr,
    Void,
}

impl Repr {
    fn ll(self) -> &'static str {
        match self {
            Repr::I1 => "i1",
            Repr::I8 => "i8",
            Repr::I16 => "i16",
            Repr::I32 => "i32",
            Repr::I64 => "i64",
            Repr::F32 => "float",
            Repr::F64 => "double",
            Repr::Ptr => "ptr",
            Repr::Void => "void",
        }
    }
    fn zero(self) -> &'static str {
        match self {
            Repr::Ptr => "null",
            Repr::F32 | Repr::F64 => "0.0",
            Repr::I1 => "false",
            _ => "0",
        }
    }
    fn is_int(self) -> bool {
        matches!(self, Repr::I1 | Repr::I8 | Repr::I16 | Repr::I32 | Repr::I64)
    }
}

pub fn repr(t: &Type) -> Repr {
    match t {
        Type::Bool => Repr::I1,
        Type::Int(i) => match i.bits() {
            8 => Repr::I8,
            16 => Repr::I16,
            32 => Repr::I32,
            _ => Repr::I64,
        },
        Type::Float(FloatTy::F64) => Repr::F64,
        Type::Float(_) => Repr::F32,
        Type::Void | Type::Never | Type::Error => Repr::Void,
        Type::Ref(false, t) => repr(t),
        _ => Repr::Ptr,
    }
}

/// Parameter/return attribute text for a repr (i1 is passed zero-extended for C interop).
fn attr(r: Repr) -> &'static str {
    if r == Repr::I1 {
        "zeroext "
    } else {
        ""
    }
}

#[derive(Clone, Debug)]
struct V {
    r: Repr,
    v: String,
    owned: bool,
}

impl V {
    fn new(r: Repr, v: impl Into<String>, owned: bool) -> V {
        V { r, v: v.into(), owned }
    }
    fn void() -> V {
        V::new(Repr::Void, "", false)
    }
    fn typed(&self) -> String {
        format!("{} {}", self.r.ll(), self.v)
    }
}

pub struct TargetInfo {
    pub triple: String,
}

pub fn triple_for(t: Target) -> String {
    let os = std::env::consts::OS;
    match (t, os) {
        (Target::Amd64, "windows") => "x86_64-pc-windows-msvc",
        (Target::I386, "windows") => "i686-pc-windows-msvc",
        (Target::Arm64, "windows") => "aarch64-pc-windows-msvc",
        (Target::Amd64, "macos") => "x86_64-apple-darwin",
        (Target::Arm64, "macos") => "aarch64-apple-darwin",
        (Target::I386, "macos") => "i686-apple-darwin",
        (Target::Amd64, _) => "x86_64-unknown-linux-gnu",
        (Target::I386, _) => "i686-unknown-linux-gnu",
        (Target::Arm64, _) => "aarch64-unknown-linux-gnu",
    }
    .to_string()
}

struct ModGen<'p> {
    p: &'p Program,
    strings: HashMap<Vec<u8>, String>,
    globals: String,
    intrinsics: BTreeSet<String>,
    closure_wrappers: BTreeSet<FuncId>,
    lists: Vec<Vec<ClassId>>,
}

/// Generates a complete LLVM module for the program.
pub fn emit_module(p: &Program, target: Target) -> String {
    let mut m = ModGen { p, strings: HashMap::new(), globals: String::new(), intrinsics: BTreeSet::new(), closure_wrappers: BTreeSet::new(), lists: Vec::new() };
    let mut funcs = String::new();
    for (i, f) in p.funcs.iter().enumerate() {
        funcs.push_str(&FnGen::generate(&mut m, i as FuncId, f));
    }
    for (sid, _) in p.selectors.iter().enumerate() {
        funcs.push_str(&m.dispatcher(sid as SelectorId));
    }
    let wrappers: Vec<FuncId> = m.closure_wrappers.iter().copied().collect();
    for f in wrappers {
        funcs.push_str(&m.closure_wrapper(f));
    }
    funcs.push_str(&m.main_fn());
    let class_table = m.class_table();
    let mut out = String::new();
    let _ = writeln!(out, "; generated by {} {}", crate::LANG_NAME, env!("CARGO_PKG_VERSION"));
    let _ = writeln!(out, "target triple = \"{}\"\n", triple_for(target));
    out.push_str(RUNTIME_DECLS);
    for i in &m.intrinsics {
        let _ = writeln!(out, "{}", i);
    }
    out.push('\n');
    let _ = writeln!(out, "@l2_depth = internal global i32 0");
    for (i, _) in p.globals.iter().enumerate() {
        let _ = writeln!(out, "@g.{} = internal global ptr null", i);
    }
    out.push_str(&class_table);
    for (i, l) in m.lists.iter().enumerate() {
        let items: Vec<String> = l.iter().map(|c| format!("i32 {}", c)).collect();
        let _ = writeln!(out, "@cl.{} = private constant [{} x i32] [{}]", i, l.len(), items.join(", "));
    }
    out.push_str(&m.globals);
    out.push('\n');
    out.push_str(&funcs);
    out
}

